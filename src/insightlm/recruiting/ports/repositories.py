"""Repositories and the unit of work for recruiting."""

from __future__ import annotations

from typing import Protocol

from insightlm.governance.ports.audit import AuditLog
from insightlm.recruiting.domain.assessment import Application, Assessment, Candidate
from insightlm.recruiting.domain.assessment_job import AssessmentJob
from insightlm.recruiting.domain.fairness import Dimension as FairnessDimension
from insightlm.recruiting.domain.fairness import SelfIdentification
from insightlm.recruiting.domain.pipeline import StageTransition
from insightlm.recruiting.domain.rubric import Requisition, Rubric
from insightlm.recruiting.domain.scorecard import Scorecard
from insightlm.shared.domain.ids import (
    ApplicationId,
    AssessmentId,
    AssessmentJobId,
    CandidateId,
    DocumentId,
    RequisitionId,
    RubricId,
    ScorecardId,
    TenantId,
    UserId,
)
from insightlm.shared.ports.uow import UnitOfWork


class RequisitionRepository(Protocol):
    async def add(self, requisition: Requisition) -> None: ...
    async def get(self, requisition_id: RequisitionId) -> Requisition | None: ...
    async def list_for_tenant(self, tenant_id: TenantId) -> list[Requisition]: ...


class RubricRepository(Protocol):
    async def add(self, rubric: Rubric) -> None: ...
    async def get(self, rubric_id: RubricId) -> Rubric | None: ...
    async def update(self, rubric: Rubric) -> None: ...
    async def latest_version(self, requisition_id: RequisitionId) -> int: ...
    async def approved_for(self, requisition_id: RequisitionId) -> Rubric | None:
        """The rubric currently in force, or None. Assessment is refused without one."""
        ...

    async def list_for_requisition(self, requisition_id: RequisitionId) -> list[Rubric]: ...


class CandidateRepository(Protocol):
    async def add(self, candidate: Candidate) -> None: ...
    async def get(self, candidate_id: CandidateId) -> Candidate | None: ...
    async def with_any_document(self, document_ids: list[DocumentId]) -> list[Candidate]: ...
    async def list_for_tenant(self, tenant_id: TenantId) -> list[Candidate]: ...


class ApplicationRepository(Protocol):
    async def add(self, application: Application) -> None: ...
    async def get(self, application_id: ApplicationId) -> Application | None: ...
    async def update(self, application: Application) -> None: ...
    async def list_for_candidate(self, candidate_id: CandidateId) -> list[Application]: ...
    async def list_for_requisition(self, requisition_id: RequisitionId) -> list[Application]: ...


class AssessmentRepository(Protocol):
    async def add(self, assessment: Assessment) -> None: ...

    async def get(self, assessment_id: AssessmentId) -> Assessment | None: ...
    async def latest_for(self, application_id: ApplicationId) -> Assessment | None: ...


class AssessmentJobRepository(Protocol):
    async def add(self, job: AssessmentJob) -> None: ...

    async def get(self, job_id: AssessmentJobId) -> AssessmentJob | None: ...

    async def update(self, job: AssessmentJob) -> None: ...

    async def active_for(self, application_id: ApplicationId) -> AssessmentJob | None:
        """The queued or running job for an application, if there is one."""
        ...

    async def latest_for_applications(
        self, application_ids: list[ApplicationId]
    ) -> dict[ApplicationId, AssessmentJob]:
        """Each application's most recent job, for showing progress on a shortlist."""
        ...


class StageTransitionRepository(Protocol):
    async def add(self, transition: StageTransition) -> None: ...
    async def list_for_application(
        self, application_id: ApplicationId
    ) -> list[StageTransition]: ...


class ScorecardRepository(Protocol):
    async def add(self, card: Scorecard, *, requisition_id: RequisitionId) -> None: ...
    async def get(self, scorecard_id: ScorecardId) -> Scorecard | None: ...
    async def update(self, card: Scorecard) -> None: ...
    async def list_for_application(self, application_id: ApplicationId) -> list[Scorecard]: ...
    async def list_for_interviewer(self, interviewer_id: UserId) -> list[Scorecard]: ...
    async def requisitions_for_interviewer(self, interviewer_id: UserId) -> set[RequisitionId]: ...


class SelfIdentificationRepository(Protocol):
    async def put(self, record: SelfIdentification) -> None: ...
    async def for_candidates(
        self, candidate_ids: list[CandidateId], dimension: FairnessDimension
    ) -> dict[CandidateId, SelfIdentification]: ...


class RecruitingUnitOfWork(UnitOfWork, Protocol):
    @property
    def requisitions(self) -> RequisitionRepository: ...
    @property
    def rubrics(self) -> RubricRepository: ...
    @property
    def candidates(self) -> CandidateRepository: ...
    @property
    def applications(self) -> ApplicationRepository: ...
    @property
    def assessments(self) -> AssessmentRepository: ...
    @property
    def assessment_jobs(self) -> AssessmentJobRepository: ...

    @property
    def transitions(self) -> StageTransitionRepository: ...
    @property
    def scorecards(self) -> ScorecardRepository: ...
    @property
    def self_identification(self) -> SelfIdentificationRepository: ...
    @property
    def audit(self) -> AuditLog: ...


class RecruitingUnitOfWorkFactory(Protocol):
    def __call__(
        self, *, tenant_id: TenantId | None = None, user_id: UserId | None = None
    ) -> RecruitingUnitOfWork: ...

"""Repositories and the unit of work for recruiting."""

from __future__ import annotations

from typing import Protocol

from insightlm.governance.ports.audit import AuditLog
from insightlm.recruiting.domain.assessment import Application, Assessment, Candidate
from insightlm.recruiting.domain.rubric import Requisition, Rubric
from insightlm.shared.domain.ids import (
    ApplicationId,
    CandidateId,
    RequisitionId,
    RubricId,
    TenantId,
    UserId,
)
from insightlm.shared.ports.uow import UnitOfWork


class RequisitionRepository(Protocol):
    async def add(self, requisition: Requisition) -> None: ...
    async def get(self, requisition_id: RequisitionId) -> Requisition | None: ...
    async def list_for_tenant(self, tenant_id: TenantId) -> list[Requisition]: ...


class RubricRepository(Protocol):
    async def add(self, rubric: Rubric) -> None: ...
    async def get(self, rubric_id: RubricId) -> Rubric | None: ...
    async def update(self, rubric: Rubric) -> None: ...
    async def latest_version(self, requisition_id: RequisitionId) -> int: ...
    async def approved_for(self, requisition_id: RequisitionId) -> Rubric | None:
        """The rubric currently in force, or None. Assessment is refused without one."""
        ...

    async def list_for_requisition(self, requisition_id: RequisitionId) -> list[Rubric]: ...


class CandidateRepository(Protocol):
    async def add(self, candidate: Candidate) -> None: ...
    async def get(self, candidate_id: CandidateId) -> Candidate | None: ...


class ApplicationRepository(Protocol):
    async def add(self, application: Application) -> None: ...
    async def get(self, application_id: ApplicationId) -> Application | None: ...
    async def list_for_requisition(self, requisition_id: RequisitionId) -> list[Application]: ...


class AssessmentRepository(Protocol):
    async def add(self, assessment: Assessment) -> None: ...
    async def latest_for(self, application_id: ApplicationId) -> Assessment | None: ...


class RecruitingUnitOfWork(UnitOfWork, Protocol):
    @property
    def requisitions(self) -> RequisitionRepository: ...
    @property
    def rubrics(self) -> RubricRepository: ...
    @property
    def candidates(self) -> CandidateRepository: ...
    @property
    def applications(self) -> ApplicationRepository: ...
    @property
    def assessments(self) -> AssessmentRepository: ...
    @property
    def audit(self) -> AuditLog: ...


class RecruitingUnitOfWorkFactory(Protocol):
    def __call__(
        self, *, tenant_id: TenantId | None = None, user_id: UserId | None = None
    ) -> RecruitingUnitOfWork: ...
